import { enforce, staticSuite, test } from 'vest';

import { AdventSection } from '@okr/shared-models';

import { ADVENT_DOOR_COUNT, ADVENT_MAX_YEAR, ADVENT_MIN_YEAR } from './advent.util';
import { baseSectionValidations } from './base-section.validations';

export const adventSectionValidations = staticSuite((model: AdventSection) => {
  baseSectionValidations(model);

  test('adventYear', '@cms/section/feature.validation.adventYearRange', () => {
    const year = model.properties?.year;
    enforce(Number.isInteger(year) && year >= ADVENT_MIN_YEAR && year <= ADVENT_MAX_YEAR).isTruthy();
  });

  // generated by createSection / rearrange, never typed: a broken list is a data error, not user input
  test('adventDoors', '@cms/section/feature.validation.adventDoorCount', () => {
    enforce(model.properties?.doors?.length ?? 0).equals(ADVENT_DOOR_COUNT);
  });
});

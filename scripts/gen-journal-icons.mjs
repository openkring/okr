#!/usr/bin/env node
/**
 * Writes libs/travel/journal/feature/src/lib/journal-icons.ts: the icons the travel journal renders, embedded
 * as `data:image/svg+xml;utf8,<svg …>` URLs (spec 1.126). The journal must work offline on the iPad for weeks,
 * longer than the imgix HTTP cache keeps an icon; ion-icon parses such a URL without a request.
 *
 * Source: the live icon repository (imgix `logo/icons/<name>.svg`). Re-run after adding an icon to the journal
 * or after changing one of these icons in the repository:  node scripts/gen-journal-icons.mjs
 */
import { writeFileSync } from 'node:fs';

const IMGIX = 'https://bkaiser.imgix.net';
const OUT = 'libs/travel/journal/feature/src/lib/journal-icons.ts';

// every icon name the journal pages, its menus and ActionSheets use, and the section editor in journal mode with its
// photo picker (header, image list, editor, article slider, album grid) — keep sorted
const NAMES = [
  'add', 'add-circle', 'airplane', 'arrow-up-circle', 'book', 'cancel', 'cancel-circle', 'chatbubble', 'checkbox-circle', 'checkmark',
  'chevron-back', 'chevron-forward', 'copy', 'download', 'edit', 'ellipsis-vertical', 'eye-off', 'eye-on', 'folder',
  'images', 'info-circle', 'map', 'navigate', 'people', 'person-add', 'play', 'reload', 'send', 'settings', 'smiley', 'swap-horizontal',
  'sync-circle', 'text', 'trash', 'video', 'warning',
];

// the section-type pictures «Sektion hinzufügen» (card-select) shows, set `section`: one per JOURNAL_SECTION_TYPES entry
const SECTION_NAMES = ['album', 'article', 'hero', 'map', 'track', 'video'];
// a journal type without its own picture in the repository borrows one: 'track' (a recorded Strecke) shows the CMS 'tracker'
const SECTION_SOURCE = { track: 'tracker' };

const icons = {};
const missing = [];

async function fetchSvg(dir, name) {
  const res = await fetch(`${IMGIX}/logo/${dir}/${name}.svg`);
  const body = res.ok ? (await res.text()).trim() : '';
  if (!res.ok || !body.includes('<svg')) {
    missing.push(`${dir}/${name} (${res.status})`);
    return undefined;
  }
  // one line, no XML prolog or comments: ion-icon looks for the <svg> element in the URL itself
  return body.replace(/<\?xml[^>]*\?>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
}

for (const name of NAMES) {
  const svg = await fetchSvg('icons', name);
  if (svg) icons[name] = `data:image/svg+xml;utf8,${svg}`;
}
// shown by <img>, not ion-icon: percent-encoded, as a '#' (a colour) would end the URL there
for (const name of SECTION_NAMES) {
  const svg = await fetchSvg('section', SECTION_SOURCE[name] ?? name);
  if (svg) icons[`section/${name}`] = `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

if (missing.length > 0) {
  console.error(`Icons not found in the repository: ${missing.join(', ')}`);
  process.exit(1);
}

const lines = Object.entries(icons).map(([name, url]) => `  '${name}': ${JSON.stringify(url)},`);
writeFileSync(OUT, `// GENERATED by scripts/gen-journal-icons.mjs — do not edit by hand.
/**
 * The travel journal's icons from our icon repository, bundled so the journal renders them offline (spec 1.126).
 * The journal pages pass them to registerBundledIcons; from then on getSvgIconUrl / the svgIcon pipe return
 * these data URLs; \`section/<name>\` entries serve the svgIcon pipe's \`section\` set. (An explicit call, not a
 * side-effect import: the libs are marked sideEffects: false.)
 */
export const JOURNAL_ICONS: Record<string, string> = {
${lines.join('\n')}
};
`);
console.log(`wrote ${OUT}: ${Object.keys(icons).length} icons`);

#!/usr/bin/env node
/**
 * Writes libs/travel/journal/feature/src/lib/journal-icons.ts: the icons the travel journal renders, embedded
 * as `data:image/svg+xml;utf8,<svg …>` URLs (spec 1.126). The journal must work offline on the iPad for weeks,
 * longer than the imgix HTTP cache keeps an icon; ion-icon parses such a URL without a request.
 *
 * Source: the live icon repository (imgix `logo/icons/<name>.svg`). Re-run after adding an icon to the journal
 * or after changing one of these icons in the repository:  node scripts/gen-journal-icons.mjs
 */
import { writeFileSync } from 'node:fs';

const IMGIX = 'https://bkaiser.imgix.net';
const OUT = 'libs/travel/journal/feature/src/lib/journal-icons.ts';

// every icon name the journal pages, its menus and ActionSheets use (keep sorted)
const NAMES = [
  'add', 'airplane', 'book', 'cancel', 'chatbubble', 'download', 'edit', 'ellipsis-vertical', 'eye-off', 'eye-on',
  'images', 'info-circle', 'map', 'navigate', 'people', 'person-add', 'reload', 'send', 'settings', 'swap-horizontal',
  'sync-circle', 'text', 'trash', 'warning',
];

const icons = {};
const missing = [];
for (const name of NAMES) {
  const res = await fetch(`${IMGIX}/logo/icons/${name}.svg`);
  const body = res.ok ? (await res.text()).trim() : '';
  if (!res.ok || !body.includes('<svg')) {
    missing.push(`${name} (${res.status})`);
    continue;
  }
  // one line, no XML prolog or comments: ion-icon looks for the <svg> element in the URL itself
  const svg = body.replace(/<\?xml[^>]*\?>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
  icons[name] = `data:image/svg+xml;utf8,${svg}`;
}

if (missing.length > 0) {
  console.error(`Icons not found in the repository: ${missing.join(', ')}`);
  process.exit(1);
}

const lines = Object.entries(icons).map(([name, url]) => `  '${name}': ${JSON.stringify(url)},`);
writeFileSync(OUT, `// GENERATED by scripts/gen-journal-icons.mjs — do not edit by hand.
/**
 * The travel journal's icons from our icon repository, bundled so the journal renders them offline (spec 1.126).
 * The journal pages pass them to registerBundledIcons; from then on getSvgIconUrl / the svgIcon pipe return
 * these data URLs. (An explicit call, not a side-effect import: the libs are marked sideEffects: false.)
 */
export const JOURNAL_ICONS: Record<string, string> = {
${lines.join('\n')}
};
`);
console.log(`wrote ${OUT}: ${Object.keys(icons).length} icons`);

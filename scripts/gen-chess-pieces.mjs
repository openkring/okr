#!/usr/bin/env node
// scripts/gen-chess-pieces.mjs — regenerates libs/games/chess/ui/src/lib/chess-pieces.ts from the
// Cburnett piece set on Wikimedia Commons, used under its BSD licence option
// (libs/games/chess/ui/licenses/LICENSE-CburnettChessPieces.txt).
//
//   node scripts/gen-chess-pieces.mjs
import { writeFileSync } from 'node:fs';

const FILES = {
  K: 'klt', Q: 'qlt', R: 'rlt', B: 'blt', N: 'nlt', P: 'plt',
  k: 'kdt', q: 'qdt', r: 'rdt', b: 'bdt', n: 'ndt', p: 'pdt',
};
const OUT = 'libs/games/chess/ui/src/lib/chess-pieces.ts';
const UA = { 'User-Agent': 'okr-chess-pieces/1.0 (https://github.com/openkring/okr)' };

const lines = [];
for (const [piece, code] of Object.entries(FILES)) {
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/Chess_${code}45.svg`;
  const res = await fetch(url, { headers: UA });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const svg = (await res.text())
    .replace(/<\?xml[^>]*>/g, '')
    .replace(/<!DOCTYPE[^>]*>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!svg.startsWith('<svg')) throw new Error(`${url}: not an SVG`);
  lines.push(`  ${piece}: 'data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}',`);
}

writeFileSync(OUT, `/**
 * Chess piece images — the Cburnett set (Colin M.L. Burnett) from Wikimedia Commons, used under
 * its BSD licence option; full text in libs/games/chess/ui/licenses/. GENERATED by
 * scripts/gen-chess-pieces.mjs — do not edit by hand.
 */
import { Piece } from '@okr/games-chess-util';

export const PIECE_IMAGES: Readonly<Record<Piece, string>> = {
${lines.join('\n')}
};
`);
console.log(`wrote ${OUT}`);
